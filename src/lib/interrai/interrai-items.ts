/**
 * Findet ein Item anhand seines Codes.
 * @param code z.B. "G2h", "C1", "A11"
 */
export function findItemByCode(code: string): InterRAIItemDefinition | undefined {
  return INTERRAI_ITEMS.find((item) => item.code === code);
}

/**
 * Gibt alle Items einer bestimmten Sektion zurück.
 * @param sektion z.B. "G", "C"
 */
export function itemsBySektion(sektion: string): InterRAIItemDefinition[] {
  return INTERRAI_ITEMS.filter((item) => item.sektion === sektion);
}

